import {createBundle} from "./node/bundle.js";
import {defaultDistributionPath, prepareDistribution} from "./node/distribution.js";
import {openBrowser} from "./node/open-browser.js";
import {readManifest} from "./node/manifest.js";
import {projectGeometry} from "./proj4/gpkg-projection.js";
import {startServer} from "./server.js";
import * as databaseAdapter from "./sqlite/sqlite-adapter.js";

export const main = async (args) => {
  const options = parseArguments(args);
  if (options.help) {
    console.log(createHelpText());
    return;
  }
  if (options.command === "bundle") {
    const output = await createBundle(options.pmtiles, options.output);
    console.log(output);
    return;
  }
  const preview = await readManifest(options.output);
  const distributionPath = options.distribution ?? await defaultDistributionPath(preview.root, preview.manifest);
  const distribution = distributionPath === preview.root
    ? preview
    : await prepareDistribution(preview.root, preview.manifest, distributionPath);
  const diagnosticLog = options.verbose ? (event) => console.error(`preview debug: ${JSON.stringify(event)}`) : undefined;
  const {server, url} = await startServer(distribution.root, {
    databaseAdapter,
    diagnosticLog,
    featureManifest: preview.manifest,
    featureRoot: preview.root,
    manifest: distribution.manifest,
    port: options.port,
    projectGeometry,
    verbose: options.verbose,
  });
  console.log(url);
  if (!options.noOpen) {
    await openBrowser(url).catch((error) => {
      console.error(`warning: browser launch failed: ${error.message}`);
    });
  }
  await waitForShutdown(server);
  if (server.previewError) throw server.previewError;
};

export const parseArguments = (args) => {
  if (args.includes("--help") || args.includes("-h")) return {help: true};
  if (args[0] === "preview") return parsePreviewArguments(args.slice(1));
  if (args[0] === "bundle") return parseBundleArguments(args.slice(1));
  return parsePreviewArguments(args);
};

